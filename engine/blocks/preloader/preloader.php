/**
 * Занавес: красный экран со знаком-раскадровкой. Работает
 * в двух сценариях.
 *
 *   загрузка страницы — экран красный с первой отрисовки,
 *     на нём отыгрывают логотипы, затем красное уезжает наверх
 *     волной и открывает страницу;
 *
 *   переход между страницами — красное выезжает снизу и накрывает
 *     экран, дальше браузер грузит новый документ, у которого
 *     экран красный уже с первой отрисовки. Логотипы и открытие
 *     достаются новой странице: так загрузка начинается сразу
 *     после закрытия, а не после логотипов.
 *
 *     красное → страница → красное → [переход] → красное → страница
 *
 * Серого слоя здесь нет и не нужно: серое — это сама страница,
 * она лежит под занавесом и открывается по мере его ухода.
 *
 * Волна — путь-лента с дугой сверху и такой же дугой снизу,
 * высотой заведомо больше экрана. Поэтому накрытие и уход это
 * один проезд снизу вверх с остановкой посередине — ни морфинга
 * d, ни GSAP с MorphSVG не нужно.
 *
 * ВАЖНО: едет путь внутри <svg>, а не сам <svg>. SVG обрезает
 * содержимое по своим границам, и если двигать его целиком,
 * вместе с ним уезжает область отсечения — у нижнего края
 * экрана открывается полоса страницы. Поэтому бокс <svg>
 * приколочен к экрану и не трансформируется никогда.
 * preserveAspectRatio="none" делает единицу пути процентом
 * экрана: координаты читаются как проценты.
 *
 * Ставится первым элементом страницы: CSS подключён в <head>,
 * поэтому занавес закрывает экран с первой отрисовки, а не после
 * того, как доедет скрипт. Уход — чистый CSS: при выключенном
 * или упавшем JS страница всё равно откроется. Скрипт нужен
 * только для закрытия перед переходом.
 */
