<?php
/**
 * Минификация HTML на выходе. Подключается из head.php, работает
 * буфером вывода: страница собирается целиком, потом отдаётся.
 *
 * Документ уходит одной строкой — так же, как у сайтов, на которые
 * мы смотрели. Опасность в этом ровно одна, и она настоящая: пробел
 * между строчными элементами — это видимый текст.
 *
 *     <a>продвижение</a> <a>блог</a>   ->   продвижениеблог
 *
 * Поэтому склейка здесь не сплошная, а по списку блочных элементов.
 * Правило из спецификации: пробел, стоящий рядом с границей блочного
 * элемента, не отображается — его можно убрать совсем. Пробел между
 * двумя строчными отображается всегда — он сжимается до одного и
 * остаётся. Отсюда:
 *
 *     <p>\n  <a>раз</a> <a>два</a>\n</p>   ->   <p><a>раз</a> <a>два</a></p>
 *
 * Перевод строки у <p> убран (сосед блочный), пробел между ссылками
 * оставлен (оба соседа строчные). У ссылок и кнопок на этом сайте
 * display:inline-block, то есть такой пробел — ещё и видимый зазор
 * между ними в раскладке, а не только в тексте.
 *
 * svg намеренно считается строчным: иконка внутри кнопки стоит рядом
 * со словом, и пробел между ними значащий. Содержимое svg (path, g,
 * use) — блочное, там пробелов не видно.
 *
 * Главное правило, как в minify.py: пробелы режутся ТОЛЬКО в коде.
 * Литерал уезжает байт в байт, и литералов здесь три вида —
 * содержимое script/style/pre/textarea (там и JSON-LD, и Метрика, и
 * преформат), значение атрибута в кавычках (многострочный content=
 * у meta description сломался бы молча) и комментарий с
 * восклицательным знаком: <!--! ... --> остаётся в выдаче, тем же
 * знаком в CSS и JS помечено предупреждение о TRIAL-шрифтах.
 *
 * Подпись студии через это не проходит вообще: она печатается в
 * footer.php за </html>, вне буфера.
 *
 * Чего фильтр не делает: не выбрасывает необязательные закрывающие
 * теги, не снимает кавычки с атрибутов, не трогает содержимое
 * скриптов. Это требует разбора HTML целиком, а выигрыш там тот же —
 * байты, которые gzip уже забрал. Весь выигрыш этого файла на /geo/:
 * 5 757 байт после gzip против 5 624, то есть 133.
 *
 * Цена буфера: первый байт уходит после сборки всей страницы. Без
 * базы и внешних запросов это доли миллисекунды, но на сайте с
 * медленным блоком буфер отложит и preload шрифтов.
 *
 * Проверка — engine/tools/check-html-min.py, запускать после правок
 * шаблонов: она сверяет текст обоих рендеров байт в байт и отдельно
 * гоняет случаи, которые это правило ломает молча.
 */

/**
 * Элементы, рядом с границей которых пробел не отображается.
 * Всё, чего здесь нет, считается строчным, и пробел рядом с ним
 * сохраняется. Список неполный намеренно: незнакомый тег попадает
 * в строчные, то есть в безопасную сторону.
 */
const RS_HTML_BLOCK = [
    'html' => 1, 'head' => 1, 'body' => 1, 'meta' => 1, 'link' => 1,
    'title' => 1, 'base' => 1, 'script' => 1, 'style' => 1, 'noscript' => 1,
    'div' => 1, 'p' => 1, 'section' => 1, 'article' => 1, 'aside' => 1,
    'header' => 1, 'footer' => 1, 'main' => 1, 'nav' => 1, 'address' => 1,
    'h1' => 1, 'h2' => 1, 'h3' => 1, 'h4' => 1, 'h5' => 1, 'h6' => 1,
    'ul' => 1, 'ol' => 1, 'li' => 1, 'dl' => 1, 'dt' => 1, 'dd' => 1,
    'table' => 1, 'thead' => 1, 'tbody' => 1, 'tfoot' => 1, 'tr' => 1,
    'td' => 1, 'th' => 1, 'caption' => 1, 'colgroup' => 1, 'col' => 1,
    'form' => 1, 'fieldset' => 1, 'legend' => 1, 'optgroup' => 1,
    'option' => 1, 'figure' => 1, 'figcaption' => 1, 'blockquote' => 1,
    'hr' => 1, 'pre' => 1, 'details' => 1, 'summary' => 1, 'dialog' => 1,
    'template' => 1, 'source' => 1, 'track' => 1,
    // Внутренности svg: текста там нет, кроме <text>, а он строчный.
    'path' => 1, 'g' => 1, 'defs' => 1, 'use' => 1, 'circle' => 1,
    'rect' => 1, 'line' => 1, 'polyline' => 1, 'polygon' => 1,
    'ellipse' => 1, 'clippath' => 1, 'mask' => 1, 'symbol' => 1,
    'lineargradient' => 1, 'radialgradient' => 1, 'stop' => 1, 'desc' => 1,
];

function rs_html_min(string $html): string
{
    // Токены: сырой элемент, комментарий, тег, текст. Кавычки в теге
    // учтены — иначе > внутри атрибута рвал бы тег пополам.
    $re = '~'
        . '(<(?:script|style|pre|textarea)\b[^>]*>.*?</(?:script|style|pre|textarea)\s*>)'
        . '|(<!--.*?-->)'
        . '|(<[a-zA-Z!/][^>"\']*(?:(?:"[^"]*"|\'[^\']*\')[^>"\']*)*>)'
        . '~si';

    $parts = preg_split($re, $html, -1, PREG_SPLIT_DELIM_CAPTURE | PREG_SPLIT_NO_EMPTY);

    // Любой сбой разбора (битый UTF-8, переполнение backtrack) — отдаём
    // страницу как есть. Сэкономленные байты того не стоят.
    if ($parts === false || $parts === null) {
        return $html;
    }

    // Первый проход: выбросить комментарии и привести теги в порядок.
    // Соседей текстового узла считаем уже по очищенному списку —
    // иначе выброшенный комментарий закрывал бы от текста настоящий
    // блочный тег рядом.
    $tokens = [];
    foreach ($parts as $p) {
        if (strncmp($p, '<!--', 4) === 0) {
            if (strncmp($p, '<!--!', 5) === 0) {
                $tokens[] = ['block', $p];   // помеченный остаётся
            }
            continue;
        }
        if ($p[0] === '<') {
            if (preg_match('~^<(script|style|pre|textarea)\b~i', $p, $m)) {
                // Литерал целиком, байт в байт. Блочность — по тегу.
                $tokens[] = [rs_html_min_kind($m[1]), $p];
            } else {
                preg_match('~^</?([a-zA-Z0-9]+)~', $p, $m);
                $tokens[] = [rs_html_min_kind($m[1] ?? ''), rs_html_min_tag($p)];
            }
            continue;
        }
        $tokens[] = ['text', $p];
    }

    // Второй проход: пробелы в тексте по соседям.
    $out = '';
    $n = count($tokens);
    for ($i = 0; $i < $n; $i++) {
        [$kind, $tok] = $tokens[$i];
        if ($kind !== 'text') {
            $out .= $tok;
            continue;
        }
        // Край документа считается блочной границей.
        $prev = $i > 0 ? $tokens[$i - 1][0] : 'block';
        $next = $i + 1 < $n ? $tokens[$i + 1][0] : 'block';
        $out .= rs_html_min_text($tok, $prev === 'block', $next === 'block');
    }

    return $out;
}

/**
 * Блочный тег или строчный. Неизвестный — строчный: ошибка в эту
 * сторону стоит одного пробела, в обратную — склеенных слов.
 */
function rs_html_min_kind(string $name): string
{
    // array_key_exists, а не isset: isset() по выражению-константе
    // не компилируется, и php -l этого не ловит — файл просто молчит.
    return array_key_exists(strtolower($name), RS_HTML_BLOCK) ? 'block' : 'inline';
}

/**
 * Текстовый узел. Все пробелы внутри схлопываются в один — это
 * делает и браузер. Пробел по краям снимается только там, где сосед
 * блочный: у строчного он отображается.
 */
function rs_html_min_text(string $t, bool $blockBefore, bool $blockAfter): string
{
    // Класс выписан байтами, и это не педантизм. В PCRE \R — «любой
    // перевод строки», а \v — «любой вертикальный пробел», и оба
    // включают байт \x85. В UTF-8 это второй байт «х»: «переехала»
    // превращалось в «перее ала». Оба раза поймала проверка, не глаза.
    $t = preg_replace('/[ \t\r\n\f\x0B]+/', ' ', $t);
    if ($t === null) {
        return '';
    }
    if (trim($t) === '') {
        // Узел из одних пробелов: исчезает, если хоть один сосед блочный.
        return ($blockBefore || $blockAfter) ? '' : ' ';
    }
    if ($blockBefore) {
        $t = ltrim($t, ' ');
    }
    if ($blockAfter) {
        $t = rtrim($t, ' ');
    }
    return $t;
}

/**
 * Внутри тега: схлопнуть пробелы между атрибутами. Значение в
 * кавычках — литерал, в него фильтр не заходит.
 */
function rs_html_min_tag(string $tag): string
{
    $chunks = preg_split('~("[^"]*"|\'[^\']*\')~', $tag, -1, PREG_SPLIT_DELIM_CAPTURE | PREG_SPLIT_NO_EMPTY);
    if ($chunks === false || $chunks === null) {
        return $tag;
    }
    $out = '';
    foreach ($chunks as $c) {
        $out .= ($c[0] === '"' || $c[0] === "'") ? $c : preg_replace('/\s+/', ' ', $c);
    }
    return $out;
}
